// Command ccnlgen turns the CNEL open data export of the national
// collective agreements in force into the table embedded by internal/ccnl.
//
// Download the export from https://www.cnel.it/archivio-contratti/contratti-open-data
// ("Contratti Collettivi Nazionali Archivio Corrente"), then run:
//
//	go run ./cmd/ccnlgen -date 2026-10-14 archivio_corrente.json > internal/ccnl/ccnl.tsv
package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"regexp"
	"slices"
	"strings"
	"time"
)

// record is one agreement in the export; only the fields used are listed.
type record struct {
	Code       string   `json:"codiceCcnl"`
	Title      string   `json:"titoloCcnl"`
	Sectors    []string `json:"settoriDescrizione"`
	Signed     string   `json:"dataStipula"`
	From       string   `json:"dataDecorrenza"`
	Until      string   `json:"dataScadenzaContrattuale"`
	Employers  []string `json:"partiDatorialiFirmatarie"`
	Unions     []string `json:"partiSindacaliFirmatarie"`
	InForce    bool     `json:"ultimoAccordoVigente"`
	Visible    bool     `json:"visibileOnline"`
	Scope      string   `json:"ambito"`
	Agreement  string   `json:"tipologiaAccordo"`
	Identifier string   `json:"identificativoAccordo"`
}

var codePattern = regexp.MustCompile(`^[A-Z][0-9A-Z]{3}$`)

func main() {
	date := flag.String("date", "", "date of the export, YYYY-MM-DD")
	flag.Parse()
	if flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "usage: ccnlgen -date YYYY-MM-DD archivio_corrente.json > internal/ccnl/ccnl.tsv")
		os.Exit(2)
	}
	if err := run(flag.Arg(0), *date, os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "ccnlgen:", err)
		os.Exit(1)
	}
}

func run(path, date string, w io.Writer) error {
	if _, err := time.Parse(time.DateOnly, date); err != nil {
		return errors.New("-date must be YYYY-MM-DD")
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var export struct {
		Data []record `json:"data"`
	}
	if err := json.Unmarshal(raw, &export); err != nil {
		return err
	}
	byCode := map[string][]record{}
	for _, r := range export.Data {
		if !r.InForce || !r.Visible || r.Scope != "Contratto collettivo nazionale" {
			continue
		}
		if !codePattern.MatchString(r.Code) || !strings.ContainsAny(r.Code, "0123456789") {
			return fmt.Errorf("agreement %s: unexpected code %q", r.Identifier, r.Code)
		}
		byCode[r.Code] = append(byCode[r.Code], r)
	}
	if len(byCode) == 0 {
		return errors.New("no agreements in force")
	}
	codes := make([]string, 0, len(byCode))
	for c := range byCode {
		codes = append(codes, c)
	}
	slices.Sort(codes)

	fmt.Fprintf(w, "# National collective agreements in force, from the CNEL open data export of %s.\n", date)
	fmt.Fprintln(w, "# Source: CNEL, Archivio nazionale dei contratti e degli accordi collettivi di lavoro,")
	fmt.Fprintln(w, "# https://www.cnel.it/archivio-contratti/contratti-open-data. License: Italian Open Data License v2.0.")
	fmt.Fprintln(w, "# Generated by cmd/ccnlgen: do not edit by hand.")
	fmt.Fprintln(w, "# code\ttitle\tsectors\tfrom\tuntil\temployers\tunions")
	for _, c := range codes {
		rs := byCode[c]
		// The latest agreement gives the period; the parties are those of
		// every agreement in force for the contract.
		latest := slices.MaxFunc(rs, func(a, b record) int { return strings.Compare(a.Signed, b.Signed) })
		var sectors, employers, unions []string
		title := ""
		for _, r := range rs {
			sectors = append(sectors, r.Sectors...)
			employers = append(employers, r.Employers...)
			unions = append(unions, r.Unions...)
			if t := clean(r.Title); len(t) > len(title) {
				title = t
			}
		}
		fmt.Fprintf(w, "%s\t%s\t%s\t%s\t%s\t%s\t%s\n", c, title, list(sectors), latest.From, latest.Until, list(employers), list(unions))
	}
	return nil
}

// clean collapses whitespace and removes the separators of the table.
func clean(s string) string {
	return strings.Join(strings.Fields(strings.NewReplacer("\t", " ", "|", " ").Replace(s)), " ")
}

// list returns the distinct, cleaned values sorted and joined by "|".
func list(vs []string) string {
	var out []string
	for _, v := range vs {
		if v = clean(v); v != "" {
			out = append(out, v)
		}
	}
	slices.Sort(out)
	return strings.Join(slices.Compact(out), "|")
}
